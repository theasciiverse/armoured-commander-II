"""Writes src/glyph_table.rs: each glyph's 2x2 pixel pattern, measured from
the original font (data/c64_8x8_ext.png in the original's folder), for
drawing the square-celled art in the terminal. A quadrant counts as set
when at least half its pixels are.

    python3 tools/glyphs.py "../../references/Armoured Commander II/data/c64_8x8_ext.png"
"""
import sys
from PIL import Image

font = Image.open(sys.argv[1]).convert('RGBA')
masks = []
for code in range(288):
    r, c = divmod(code, 16)
    bits = 0
    for n, (x0, y0) in enumerate([(0, 0), (4, 0), (0, 4), (4, 4)]):
        on = sum(1 for x in range(x0, x0 + 4) for y in range(y0, y0 + 4)
                 if font.getpixel((c * 8 + x, r * 8 + y))[3] > 128)
        if on >= 8:
            bits |= 1 << n
    masks.append(bits)
rows = []
for i in range(0, 288, 16):
    rows.append('    ' + ', '.join('0b' + format(m, '04b') for m in masks[i:i + 16]) + ',')
out = '''// Generated by tools/glyphs.py from the original font; do not edit.

/// Each glyph's 2x2 pixels, measured from the font: bit 0 top left, 1 top
/// right, 2 bottom left, 3 bottom right.
pub const QUADS: [u8; 288] = [
%s
];
''' % '\n'.join(rows)
open('src/glyph_table.rs', 'w').write(out)
print('ok')
